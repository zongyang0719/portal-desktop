import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, context } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "demo/sidebar.html");
const licenses = await Promise.all(["react", "react-dom", "scheduler", "lucide-react", "marked", "highlight.js"].map(async name =>
  `${name}\n${await readFile(path.join(root, "node_modules", name, name === "marked" ? "LICENSE.md" : "LICENSE"), "utf8")}`));

const options = {
  absWorkingDir: root,
  entryPoints: ["demo/sidebar.tsx"],
  bundle: true,
  write: false,
  outfile: "sidebar.js",
  format: "iife",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  minify: true,
  charset: "utf8",
  plugins: [{
    name: "standalone-sidebar-html",
    setup(builder) {
      builder.onEnd(async result => {
        if (result.errors.length) return;
        const js = result.outputFiles.find(file => file.path.endsWith(".js")).text;
        const css = result.outputFiles.find(file => file.path.endsWith(".css")).text;
        // Inline both bundles so file:// needs no server, module fetches or CDN.
        await writeFile(output, `<!doctype html>
<!-- Generated by npm run build:demo from the desktop component. Do not edit this file. -->
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Portal · Sidebar 预览</title>
  <style>${css.replace(/<\/style/gi, "<\\/style")}</style>
</head>
<body>
  <div id="root"></div>
  <noscript>请启用 JavaScript 以预览场景边栏。</noscript>
  <script>${js.replace(/<\/script/gi, "<\\/script")}</script>
</body>
</html>
<!-- Third-party licenses\n${licenses.join("\n\n").replaceAll("-->", "-- >")} -->
`);
        console.log("Built demo/sidebar.html — open directly in a browser.");
      });
    },
  }],
};

if (process.argv.includes("--watch")) {
  const builder = await context(options);
  await builder.watch();
  console.log("Watching shared sidebar component and styles; refresh the browser after edits.");
} else {
  await build(options);
}
