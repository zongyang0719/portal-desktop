import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, context } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));

/** Bundle a real component entry as an offline HTML file, including licenses. */
export async function buildComponentDemo({ name, title, command, watch = false }) {
  const output = path.join(root, `demo/${name}.html`);
  const options = {
    absWorkingDir: root, entryPoints: [`demo/${name}.tsx`], bundle: true, write: false,
    outfile: `${name}.js`, format: "iife", platform: "browser", target: "es2022",
    jsx: "automatic", define: { "process.env.NODE_ENV": '"production"', "import.meta.env.DEV": "false" }, minify: true,
    charset: "utf8", metafile: true,
    plugins: [{ name: "standalone-component-html", setup(builder) {
      builder.onEnd(async result => {
        if (result.errors.length) return;
        const packages = new Set(Object.keys(result.metafile.inputs).flatMap(input => {
          const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
          return match ? [match[1]] : [];
        }));
        const licenses = await Promise.all([...packages].sort().map(async name => {
          for (const filename of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md"]) {
            try { return `${name}\n${await readFile(path.join(root, "node_modules", name, filename), "utf8")}`; }
            catch (error) { if (error.code !== "ENOENT") throw error; }
          }
          throw new Error(`No license file found for bundled dependency ${name}`);
        }));
        const js = result.outputFiles.find(file => file.path.endsWith(".js")).text;
        const css = result.outputFiles.find(file => file.path.endsWith(".css"))?.text || "";
        await writeFile(output, `<!doctype html>
<!-- Generated by ${command} from shared components. Do not edit this file. -->
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title}</title>
  <style>${css.replace(/<\/style/gi, "<\\/style")}</style>
</head>
<body>
  <div id="root"></div>
  <noscript>请启用 JavaScript 以查看组件预览。</noscript>
  <script>${js.replace(/<\/script/gi, "<\\/script")}</script>
</body>
</html>
<!-- Third-party licenses\n${licenses.join("\n\n").replaceAll("-->", "-- >")} -->
`);
        console.log(`Built demo/${name}.html — open directly in a browser.`);
      });
    }}],
  };
  if (watch) {
    const builder = await context(options); await builder.watch();
    console.log(`Watching shared ${name} components; refresh after edits.`);
  } else await build(options);
}
